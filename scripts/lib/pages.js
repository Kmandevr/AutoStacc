// Templates for the generated pages: one per release (/music/<id>), product (/shop/<id>) and news post (/news/<id>).
// Each returns { file, page, html }: `page` is the metadata for lib/head.js, `html` the whole document.
const { abs } = require("./data");
const H = require("./head");

const { esc, isUrl } = H;
const GENERATED = "<!-- Generated by scripts/build.js from data/. Don't edit: change the data, then run node scripts/build.js. -->";
const suffix = (SITE) => " · " + SITE.artist;
const money = (n) => "$" + Number(n).toFixed(2);
const fmtDate = (s) => {
  const [y, m, d] = s.split("-").map(Number);
  return new Date(Date.UTC(y, m - 1, d)).toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric", timeZone: "UTC" });
};
// Search descriptions read best under ~160 characters; cut at a word boundary.
const clip = (s, n = 160) => (s.length <= n ? s : s.slice(0, s.lastIndexOf(" ", n - 1)).replace(/[,.;:]$/, "") + "…");

function shell(SITE, { page, section, styles, scripts, main }) {
  return `<!doctype html>
${GENERATED}
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  ${H.headBlock(SITE, page)}
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@400;700&family=VT323&display=swap" rel="stylesheet">
  <link rel="icon" href="/img/favicon.png" type="image/png">
  <link rel="apple-touch-icon" href="/img/apple-touch-icon.png">
  <meta name="theme-color" content="#000000">
  <meta name="color-scheme" content="dark">
${["base", "layout", "eggs", ...styles].map((s) => `  <link rel="stylesheet" href="/css/${s}.css">`).join("\n")}
</head>
<body data-page="${section}-item" data-section="${section}">
  <header id="site-header"></header>

  <main id="main">
${main}
  </main>

  <footer id="site-footer"></footer>

${["data/site.js", ...scripts.filter((s) => s.startsWith("data/")), "js/util.js", "js/layout.js", "js/sound.js",
    ...scripts.filter((s) => s.startsWith("js/")), "js/eggs.js", "js/terminal.js", "js/motion.js"]
    .map((s) => `  <script src="/${s}"></script>`).join("\n")}
</body>
</html>
`;
}

// Visible breadcrumb trail; the same list goes into BreadcrumbList structured data.
function crumbNav(crumbs) {
  const items = crumbs.map(([name, p], i) =>
    i === crumbs.length - 1 ? `<li aria-current="page">${esc(name)}</li>` : `<li><a href="${esc(p)}">${esc(name)}</a></li>`);
  return `<nav class="crumbs" aria-label="Breadcrumb"><ol>${items.join("")}</ol></nav>`;
}

function hero(crumbs, kicker, title, sub) {
  return `    <div class="page-hero detail-hero">
      <div class="wrap">
        ${crumbNav(crumbs)}
        <p class="detail-kicker">${kicker}</p>
        <h1 class="glitch" data-text="${esc(title)}">${esc(title)}</h1>
        ${sub ? `<p>${sub}</p>` : ""}
      </div>
    </div>`;
}

// <picture> with WebP and JPEG sizes when the data lists them.
function picture(img, sizes, eager) {
  const set = (type) => (img.srcset || []).filter((s) => s.type === type).map((s) => `/${s.src} ${s.width}w`).join(", ");
  const webp = set("image/webp"), jpeg = set("image/jpeg");
  return `<picture>${webp ? `<source type="image/webp" srcset="${esc(webp)}" sizes="${sizes}">` : ""}<img src="/${esc(img.src)}"${jpeg ? ` srcset="${esc(jpeg)}" sizes="${sizes}"` : ""} width="${img.width}" height="${img.height}" alt="${esc(img.alt)}" decoding="async"${eager ? ' fetchpriority="high"' : ' loading="lazy"'}></picture>`;
}

const tint = (hue = 300) => (hue >= 90 && hue < 210 ? "green" : "purple");
const productCover = (p, eager) => p.image
  ? `<div class="product-art">${picture(p.image, "(max-width: 860px) 100vw, 480px", eager)}</div>`
  : `<div class="product-art cover tint-${tint(p.hue)}" aria-hidden="true"><span>${esc(p.title.split(" — ")[0])}</span></div>`;

const linkButtons = (links) => links.map((l) => `<a class="btn ghost" href="${esc(l.url)}" target="_blank" rel="noopener">${esc(l.name)}</a>`).join("");

function productTile(p) {
  return `<li><a class="tile" href="/shop/${esc(p.id)}"><span class="tag">${esc(p.category)}</span><strong>${esc(p.title)}</strong><span class="price">${money(p.price)}</span></a></li>`;
}

// ---------- release ----------
function releasePage(SITE, data, r) {
  const url = abs(SITE, "/music/" + r.id);
  const year = r.date.slice(0, 4);
  const crumbs = [["Home", "/"], ["Music", "/music"], [r.title, "/music/" + r.id]];
  const links = (r.links || []).filter((l) => isUrl(l.url));
  const tracks = r.tracks || [];
  const related = data.products.filter((p) => p.release === r.id);
  const posts = data.news.filter((n) => n.release === r.id);
  const total = tracks.reduce((t, x) => { const [m, s] = x.duration.split(":").map(Number); return t + m * 60 + s; }, 0);
  const length = `${Math.floor(total / 60)}:${String(total % 60).padStart(2, "0")}`;
  const page = {
    path: "/music/" + r.id,
    title: `${r.title} (${r.type.toLowerCase()})${suffix(SITE)}`,
    description: clip(r.description),
    index: true,
    ogType: "music.album",
    image: r.artwork,
    og: { "music:musician": abs(SITE, "/"), "music:release_date": r.date },
    schema: [
      H.webPage(SITE, { path: "/music/" + r.id, title: `${r.title} (${r.type.toLowerCase()})${suffix(SITE)}`, description: clip(r.description) },
        "WebPage", { mainEntity: { "@id": url + "#release" }, breadcrumb: H.breadcrumbs(SITE, crumbs) }),
      H.album(SITE, r, url)
    ]
  };
  const main = `${hero(crumbs, `${esc(r.type)} · ${year}`, r.title, `by <a href="/">${esc(SITE.artist)}</a>`)}

    <section>
      <div class="wrap release">
        ${r.artwork ? `<figure class="release-art">${picture(r.artwork, "(max-width: 860px) 100vw, 480px", true)}</figure>` : ""}
        <div class="release-info">
          <p class="lede">${esc(r.description)}</p>
          <dl class="facts">
            <dt>Artist</dt><dd><a href="/">${esc(SITE.artist)}</a></dd>
            <dt>Release</dt><dd>${esc(r.type)}</dd>
            <dt>Released</dt><dd><time datetime="${esc(r.date)}">${fmtDate(r.date)}</time></dd>
            <dt>Length</dt><dd>${tracks.length} track${tracks.length === 1 ? "" : "s"}, ${length}</dd>
            ${r.upc ? `<dt>UPC</dt><dd>${esc(r.upc)}</dd>` : ""}
          </dl>
          ${links.length ? `<p class="platforms-label">Stream ${esc(r.title)} on</p>
          <div class="platforms">${linkButtons(links)}</div>` : ""}
        </div>
      </div>
    </section>

    <section class="alt">
      <div class="wrap">
        <div class="section-head"><h2>Listen</h2></div>
        <div id="listen-player" data-release="${esc(r.id)}"></div>
      </div>
    </section>

    <section>
      <div class="wrap">
        <div class="section-head"><h2>Tracklist</h2></div>
        <ol class="tracklist">
          ${tracks.map((t) => `<li><span class="track-title">${esc(t.title)}</span><time datetime="${H.isoDuration(t.duration)}">${esc(t.duration)}</time>${t.isrc ? `<span class="isrc">ISRC ${esc(t.isrc)}</span>` : ""}</li>`).join("\n          ")}
        </ol>
        ${(r.credits || []).length ? `<h2 class="sub-head">Credits</h2>
        <dl class="facts">${r.credits.map((c) => `<dt>${esc(c.role)}</dt><dd>${esc(c.name)}</dd>`).join("")}</dl>` : ""}
      </div>
    </section>
${related.length ? `
    <section class="alt">
      <div class="wrap">
        <div class="section-head"><h2>From the shop</h2><a href="/shop">Everything &rarr;</a></div>
        <ul class="tiles">${related.map(productTile).join("")}</ul>
      </div>
    </section>
` : ""}${posts.length ? `
    <section>
      <div class="wrap">
        <div class="section-head"><h2>News</h2><a href="/news">All updates &rarr;</a></div>
        <ul class="tiles">${posts.map((n) => `<li><a class="tile" href="/news/${esc(n.id)}"><span class="tag">${esc(n.tag || "Update")}</span><strong>${esc(n.title)}</strong><time datetime="${esc(n.date)}">${fmtDate(n.date)}</time></a></li>`).join("")}</ul>
      </div>
    </section>
` : ""}
    <section class="alt">
      <div class="wrap detail-more">
        <a class="btn ghost" href="/music">All music</a>
        <a class="btn ghost" href="/shop">Shop downloads</a>
      </div>
    </section>`;
  return { file: `music/${r.id}.html`, page, html: shell(SITE, { page, section: "music", styles: ["music", "detail"], scripts: ["data/music.js", "js/music.js"], main }) };
}

// ---------- product ----------
function productPage(SITE, data, p) {
  const url = abs(SITE, "/shop/" + p.id);
  const crumbs = [["Home", "/"], ["Shop", "/shop"], [p.title, "/shop/" + p.id]];
  const release = data.releases.find((r) => r.id === p.release);
  const buyable = isUrl(p.checkoutUrl);
  const more = data.products.filter((x) => x.id !== p.id && x.category === p.category).slice(0, 3);
  const others = more.length ? more : data.products.filter((x) => x.id !== p.id).slice(0, 3);
  const title = `${p.title}${suffix(SITE)}`;
  const description = clip(`${p.title}: ${p.description} ${p.category} from ${SITE.artist}, ${money(p.price)}.`);
  const page = {
    path: "/shop/" + p.id,
    title,
    description,
    // Placeholder products are shown in the shop, but their pages stay out of search.
    index: !p.draft,
    ogType: "product",
    image: p.image,
    og: { "product:price:amount": Number(p.price).toFixed(2), "product:price:currency": SITE.currency || "USD" },
    schema: p.draft ? [] : [
      H.webPage(SITE, { path: "/shop/" + p.id, title, description }, "ItemPage",
        { mainEntity: { "@id": url + "#product" }, breadcrumb: H.breadcrumbs(SITE, crumbs) }),
      H.product(SITE, p, url, release)
    ]
  };
  const main = `${hero(crumbs, esc(p.category), p.title, `by <a href="/">${esc(SITE.artist)}</a>`)}

    <section>
      <div class="wrap product">
        ${productCover(p, true)}
        <div class="product-info">
          <p class="lede">${esc(p.description)}</p>
          ${p.preview ? `<p>${esc(p.preview)}</p>` : ""}
          <dl class="facts">
            <dt>Type</dt><dd>${esc(p.category)}</dd>
            <dt>Format</dt><dd>Digital download</dd>
            <dt>Price</dt><dd class="price">${money(p.price)}</dd>
            <dt>Status</dt><dd>${buyable ? "Available now" : "Coming soon"}</dd>
            ${release ? `<dt>Release</dt><dd><a href="/music/${esc(release.id)}">${esc(release.title)}</a></dd>` : ""}
          </dl>
          <div class="detail-buy">
            ${buyable ? `<a class="btn" href="${esc(p.checkoutUrl)}" target="_blank" rel="noopener">Buy</a>` : `<span class="btn" aria-disabled="true">Coming soon</span>`}
          </div>
          <p class="note">Payment and the download are handled by our checkout provider. This site never sees your card details.</p>
        </div>
      </div>
    </section>
${others.length ? `
    <section class="alt">
      <div class="wrap">
        <div class="section-head"><h2>More downloads</h2><a href="/shop">Everything &rarr;</a></div>
        <ul class="tiles">${others.map(productTile).join("")}</ul>
      </div>
    </section>
` : ""}`;
  return { file: `shop/${p.id}.html`, page, html: shell(SITE, { page, section: "shop", styles: ["shop", "detail"], scripts: [], main }) };
}

// ---------- news post ----------
function newsPage(SITE, data, n) {
  const url = abs(SITE, "/news/" + n.id);
  const crumbs = [["Home", "/"], ["News", "/news"], [n.title, "/news/" + n.id]];
  const release = data.releases.find((r) => r.id === n.release);
  const image = (release && release.artwork) || SITE.image;
  const title = `${n.title}${suffix(SITE)}`;
  const description = clip(n.summary || n.title);
  const page = {
    path: "/news/" + n.id,
    title,
    description,
    index: true,
    ogType: "article",
    image,
    og: { "article:published_time": n.date, ...(n.tag && { "article:section": n.tag }) },
    schema: [
      H.webPage(SITE, { path: "/news/" + n.id, title, description }, "WebPage",
        { mainEntity: { "@id": url + "#article" }, breadcrumb: H.breadcrumbs(SITE, crumbs) }),
      H.article(SITE, n, url, image)
    ]
  };
  const main = `${hero(crumbs, `${esc(n.tag || "Update")} · <time datetime="${esc(n.date)}">${fmtDate(n.date)}</time>`, n.title, "")}

    <section>
      <div class="wrap article">
        <div class="article-body">
          ${n.body || `<p>${esc(n.summary || "")}</p>`}
        </div>
        ${release ? `<a class="tile release-tile" href="/music/${esc(release.id)}">${release.artwork ? picture(release.artwork, "160px", false) : ""}<span><span class="tag">${esc(release.type)}</span><strong>${esc(release.title)}</strong><span>Release page &rarr;</span></span></a>` : ""}
      </div>
    </section>

    <section class="alt">
      <div class="wrap detail-more">
        <a class="btn ghost" href="/news">All news</a>
        <a class="btn ghost" href="/music">Music</a>
      </div>
    </section>`;
  return { file: `news/${n.id}.html`, page, html: shell(SITE, { page, section: "news", styles: ["news", "detail"], scripts: [], main }) };
}

module.exports = { GENERATED, releasePage, productPage, newsPage, clip };
