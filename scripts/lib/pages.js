// Templates for the generated pages: one per product (/shop/<id>, a platform page), and for each project one per
// release (/<creator>/<project>/music/<id>) and news post (/<creator>/<project>/news/<id>), in the project's skin.
// Each returns { file, page, html }: `page` is the metadata for lib/head.js, `html` the whole document.
const { abs, projectPath } = require("./data");
const H = require("./head");
const { relationsOf } = require("./relations");
const { resolveRef } = require("./platform");
const { licenseBox } = require("./rich-text");
const { details: productDetails } = require("./catalog");
const V = require("../../server/discovery/vocabulary.js");

const { esc, isUrl } = H;
const GENERATED = "<!-- Generated by scripts/build.js from data/. Don't edit: change the data, then run node scripts/build.js. -->";
// Titles end with the page's owner: the project's name on its pages, AutoStacc on platform pages.
const suffix = (name) => " · " + name;
// A project's pages name the project and the site: "HAIL (single) · Glitches & Stitches · AutoStacc".
const projectSuffix = (SITE, name) => suffix(name) + suffix(SITE.name);
const money = (n) => "$" + Number(n).toFixed(2);
const fmtDate = (s) => {
  const [y, m, d] = s.split("-").map(Number);
  return new Date(Date.UTC(y, m - 1, d)).toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric", timeZone: "UTC" });
};
// Search descriptions read best under ~160 characters; cut at a word boundary.
const clip = (s, n = 160) => {
  if (s.length <= n) return s;
  const cut = s.lastIndexOf(" ", n - 1);
  return s.slice(0, cut > 0 ? cut : n - 1).replace(/[,.;:]$/, "") + "…";
};

// Fonts: AutoStacc's on every page, plus the pixel font for a project skin that uses it.
const FONTS = "https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700;800&family=JetBrains+Mono:wght@400;600;700";

// The whole document. project: the project whose page this is (its frame, skin and sounds), or null for a platform
// page. projectPage: which of the project's pages lights up in its header ("music", "news").
// look: on a platform page, the project whose look it wears (a product page wears its creator's look).
function shell(SITE, { page, section, styles, scripts, main, project = null, projectPage = "", look = null }) {
  const skin = project && project.skin;
  const lookOf = skin ? project : look && look.skin ? look : null;
  const sounds = project && project.sounds;
  const css = ["core", "platform", "layout", ...(project ? ["project-frame"] : []), ...styles, ...(lookOf ? [`projects/${lookOf.id}/look`] : []), ...(skin ? [`projects/${project.id}/skin`] : []), ...(sounds ? ["eggs"] : [])];
  const js = ["data/site.js", "data/projects.js", ...scripts.filter((s) => s.startsWith("data/")), "js/util.js", project ? "js/project-frame.js" : "js/layout.js", "js/account-nav.js",
    ...(sounds ? ["js/sound.js"] : []), ...scripts.filter((s) => s.startsWith("js/")), ...(sounds ? ["js/eggs.js", "js/terminal.js"] : []), "js/motion.js"];
  return `<!doctype html>
${GENERATED}
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  ${H.headBlock(SITE, page)}
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="${FONTS}${skin ? "&amp;family=VT323" : ""}&amp;display=swap" rel="stylesheet">
  <link rel="icon" href="/img/favicon.png" type="image/png">
  <link rel="apple-touch-icon" href="/img/apple-touch-icon.png">
  <meta name="theme-color" content="#111318">
  <meta name="color-scheme" content="light dark">
  <script src="/js/theme.js"></script>
${css.map((s) => `  <link rel="stylesheet" href="/css/${s}.css">`).join("\n")}
</head>
<body data-page="${section}-item" data-section="${section}"${project ? ` data-project="${esc(project.id)}" data-project-page="${esc(projectPage)}"` : ""}>
  <header id="site-header"></header>

  <main id="main" class="${skin ? `skin-${esc(project.id)}` : `platform${lookOf ? ` look-${esc(lookOf.id)}` : ""}`}">
${main}
  </main>

  <footer id="site-footer"></footer>

${js.map((s) => `  <script src="/${s}"></script>`).join("\n")}
</body>
</html>
`;
}

// Visible breadcrumb trail; the same list goes into BreadcrumbList structured data.
function crumbNav(crumbs) {
  const items = crumbs.map(([name, p], i) =>
    i === crumbs.length - 1 ? `<li aria-current="page">${esc(name)}</li>` : `<li><a href="${esc(p)}">${esc(name)}</a></li>`);
  return `<nav class="crumbs" aria-label="Breadcrumb"><ol>${items.join("")}</ol></nav>`;
}

function hero(crumbs, kicker, title, sub) {
  return `    <div class="page-hero detail-hero">
      <div class="wrap">
        ${crumbNav(crumbs)}
        <p class="detail-kicker">${kicker}</p>
        <h1 class="glitch" data-text="${esc(title)}">${esc(title)}</h1>
        ${sub ? `<p>${sub}</p>` : ""}
      </div>
    </div>`;
}

// <picture> with WebP and JPEG sizes when the data lists them.
function picture(img, sizes, eager) {
  const set = (type) => (img.srcset || []).filter((s) => s.type === type).map((s) => `/${s.src} ${s.width}w`).join(", ");
  const webp = set("image/webp"), jpeg = set("image/jpeg");
  return `<picture>${webp ? `<source type="image/webp" srcset="${esc(webp)}" sizes="${sizes}">` : ""}<img src="/${esc(img.src)}"${jpeg ? ` srcset="${esc(jpeg)}" sizes="${sizes}"` : ""} width="${img.width}" height="${img.height}" alt="${esc(img.alt)}" decoding="async"${eager ? ' fetchpriority="high"' : ' loading="lazy"'}></picture>`;
}

const tint = (hue = 300) => (hue >= 90 && hue < 210 ? "green" : "purple");
const productCover = (p, eager, types) => p.image
  ? `<div class="product-art">${picture(p.image, "(max-width: 860px) 100vw, 480px", eager)}</div>`
  : `<div class="product-art cover tint-${tint(p.hue)}" data-track="${esc(((types || {})[p.type] || {}).track || "")}" aria-hidden="true"><span>${esc(p.title.split(" — ")[0])}</span></div>`;

// The creator that owns a project (data/creators.js), as a breadcrumb: [name, its profile address].
const ownerCrumb = (data, project) => {
  const c = (data.creators || []).find((x) => x.id === project.creator);
  return c ? [[c.name, "/" + c.id]] : [];
};
// The project that created something (data/projects.js); the build has already checked the link exists.
const creatorOf = (data, x) => data.projects.find((p) => p.id === x.project);
const byline = (c) => `by <a href="${esc(projectPath(c.id))}">${esc(c.name)}</a>`;
const releasePath = (r) => projectPath(r.project, "music", r.id);
const newsPath = (n) => projectPath(n.project, "news", n.id);

// Where a "kind:id" reference lives on the site (only published things get a link).
function refLink(data, ref) {
  const [kind, id] = ref.split(":");
  const item = resolveRef(data, ref);
  const name = (item && (item.title || item.question)) || id;
  const href = kind === "release" && data.releases.some((r) => r.id === id) ? releasePath(item)
    : kind === "product" && item && !item.draft ? `/shop/${id}` : "";
  return href ? `<a href="${esc(href)}">${esc(name)}</a>` : esc(name);
}

// "Built from" / "Featured in" lists for one thing; empty when it has no relationships.
function relationsSection(data, ref) {
  const { outgoing, incoming } = relationsOf(data, ref);
  const groups = [...outgoing, ...incoming];
  if (!groups.length) return "";
  return `
    <section class="alt">
      <div class="wrap">
        <div class="section-head"><h2>Connections</h2></div>
        <dl class="facts relations">${groups.map((g) => `<dt>${esc(g.label)}</dt><dd><ul>${g.refs.map((r) => `<li>${refLink(data, r)}</li>`).join("")}</ul></dd>`).join("")}</dl>
      </div>
    </section>
`;
}

const linkButtons = (links) => links.map((l) => `<a class="btn ghost" href="${esc(l.url)}" target="_blank" rel="noopener">${esc(l.name)}</a>`).join("");

// A store item opens its own page (the same address js/util.js shopItemPath makes).
const shopItemPath = (p) => `/shop/${encodeURIComponent(p.id)}`;
function productTile(p) {
  return `<li><a class="tile" href="${esc(shopItemPath(p))}"><span class="tag">${esc(p.category)}</span><strong>${esc(p.title)}</strong><span class="price">${p.price ? money(p.price) : "Free"}</span></a></li>`;
}

// ---------- release ----------
function releasePage(SITE, data, r) {
  const creator = creatorOf(data, r);
  const home = projectPath(creator.id);
  const url = abs(SITE, releasePath(r));
  const year = r.date.slice(0, 4);
  const crumbs = [["Home", "/"], ...ownerCrumb(data, creator), [creator.name, home], ["Music", home + "/music"], [r.title, releasePath(r)]];
  const title = `${r.title} (${r.type.toLowerCase()})${projectSuffix(SITE, creator.name)}`;
  const links = (r.links || []).filter((l) => isUrl(l.url));
  const tracks = r.tracks || [];
  const related = data.products.filter((p) => p.release === r.id);
  const posts = data.news.filter((n) => n.release === r.id);
  const total = tracks.reduce((t, x) => { const [m, s] = String(x.duration || "0:00").split(":").map(Number); return t + m * 60 + s; }, 0);
  const length = `${Math.floor(total / 60)}:${String(total % 60).padStart(2, "0")}`;
  const page = {
    path: releasePath(r),
    title,
    description: clip(r.description),
    index: true,
    ogType: "music.album",
    image: r.artwork,
    og: { "music:musician": abs(SITE, home), "music:release_date": r.date },
    schema: [
      H.webPage(SITE, { path: releasePath(r), title, description: clip(r.description) },
        "WebPage", { mainEntity: { "@id": url + "#release" }, breadcrumb: H.breadcrumbs(SITE, crumbs) }),
      H.album(SITE, r, url, creator)
    ]
  };
  const main = `${hero(crumbs, `${esc(r.type)} · ${year}`, r.title, byline(creator))}

    <section>
      <div class="wrap release">
        ${r.artwork ? `<figure class="release-art">${picture(r.artwork, "(max-width: 860px) 100vw, 480px", true)}</figure>` : ""}
        <div class="release-info">
          <p class="lede">${esc(r.description)}</p>
          <dl class="facts">
            <dt>Artist</dt><dd><a href="${esc(home)}">${esc(creator.name)}</a></dd>
            <dt>Release</dt><dd>${esc(r.type)}</dd>
            <dt>Released</dt><dd><time datetime="${esc(r.date)}">${fmtDate(r.date)}</time></dd>
            <dt>Length</dt><dd>${tracks.length} track${tracks.length === 1 ? "" : "s"}, ${length}</dd>
            ${r.upc ? `<dt>UPC</dt><dd>${esc(r.upc)}</dd>` : ""}
          </dl>
          ${links.length ? `<p class="platforms-label">Stream ${esc(r.title)} on</p>
          <div class="platforms">${linkButtons(links)}</div>` : ""}
        </div>
      </div>
    </section>

    <section class="alt">
      <div class="wrap">
        <div class="section-head"><h2>Listen</h2></div>
        <div data-listen data-release="${esc(r.id)}"></div>
      </div>
    </section>

    <section>
      <div class="wrap">
        <div class="section-head"><h2>Tracklist</h2></div>
        <ol class="tracklist">
          ${tracks.map((t) => `<li><span class="track-title">${esc(t.title)}</span><time datetime="${H.isoDuration(t.duration)}">${esc(t.duration)}</time>${t.isrc ? `<span class="isrc">ISRC ${esc(t.isrc)}</span>` : ""}</li>`).join("\n          ")}
        </ol>
        ${(r.credits || []).length ? `<h2 class="sub-head">Credits</h2>
        <dl class="facts">${r.credits.map((c) => `<dt>${esc(c.role)}</dt><dd>${esc(c.name)}</dd>`).join("")}</dl>` : ""}
      </div>
    </section>
${relationsSection(data, "release:" + r.id)}${related.length ? `
    <section class="alt">
      <div class="wrap">
        <div class="section-head"><h2>From the shop</h2><a href="/shop">Everything &rarr;</a></div>
        <ul class="tiles">${related.map(productTile).join("")}</ul>
      </div>
    </section>
` : ""}${posts.length ? `
    <section>
      <div class="wrap">
        <div class="section-head"><h2>News</h2><a href="${esc(home)}/news">All updates &rarr;</a></div>
        <ul class="tiles">${posts.map((n) => `<li><a class="tile" href="${esc(newsPath(n))}"><span class="tag">${esc(n.tag || "Update")}</span><strong>${esc(n.title)}</strong><time datetime="${esc(n.date)}">${fmtDate(n.date)}</time></a></li>`).join("")}</ul>
      </div>
    </section>
` : ""}
    <section class="alt">
      <div class="wrap detail-more">
        <a class="btn ghost" href="${esc(home)}/music">All music</a>
        <a class="btn ghost" href="/shop">Shop downloads</a>
      </div>
    </section>`;
  return { file: releasePath(r).slice(1) + ".html", page, html: shell(SITE, { page, section: "music", styles: ["music", "detail"], scripts: ["data/music.js", "js/music.js"], main, project: creator, projectPage: "music" }) };
}

// ---------- product ----------
// The buy area is a static fallback inside data-buy; js/store.js replaces it with the live control (Add to cart,
// Get it free, STACC'D + library link) from the store API. Drafts stay "Coming soon".
function productPage(SITE, data, p) {
  const url = abs(SITE, "/shop/" + p.id);
  const crumbs = [["Home", "/"], ["Store", "/shop"], [p.title, "/shop/" + p.id]];
  const release = data.releases.find((r) => r.id === p.release);
  const buyable = !p.draft;
  const type = data.productTypes[p.type] || {};
  const price = p.price ? money(p.price) : "Free";
  // More from the same project first, so the page reads as part of the project's catalog.
  const others = data.products.filter((x) => x.id !== p.id && x.project === p.project).slice(0, 3);
  const title = `${p.title}${suffix(SITE.name)}`;
  const creator = creatorOf(data, p);
  // What the product delivers, as Pacs within their Stacclets (data/pacs.js): products expose their contents.
  const pacs = (p.pacs || []).map((id) => data.pacs.find((x) => x.id === id)).filter(Boolean)
    .map((x) => ({ pac: x, stacclet: data.stacclets.find((s) => s.id === x.stacclet) }));
  const description = clip(`${p.title}: ${p.description} ${p.category} from ${creator.name}, ${price}.`);
  const page = {
    path: "/shop/" + p.id,
    title,
    description,
    // Placeholder products are shown in the shop, but their pages stay out of search.
    index: !p.draft,
    ogType: "product",
    image: p.image,
    og: { "product:price:amount": Number(p.price).toFixed(2), "product:price:currency": p.currency },
    schema: p.draft ? [] : [
      H.webPage(SITE, { path: "/shop/" + p.id, title, description }, "ItemPage",
        { mainEntity: { "@id": url + "#product" }, breadcrumb: H.breadcrumbs(SITE, crumbs) }),
      H.product(SITE, p, url, release, creator)
    ]
  };
  const preview = p.preview && type.preview !== "none"
    ? `<figure class="preview">
            <figcaption>${esc(p.preview.label || "Preview")}</figcaption>
            <audio controls preload="none" src="/media/previews/${esc(p.preview.file)}" data-preview="${esc(p.id)}"></audio>
          </figure>`
    : "";
  const facts = Object.entries(p.metadata || {}).map(([k, v]) => `<dt>${esc(k)}</dt><dd>${esc(v)}</dd>`).join("");
  // Structured details from the store vocabulary (the same ones the store filters by), only those the data states.
  const d = productDetails(p, data.projects);
  const FIELDS = [["Contents", "contents"], ["File formats", "format"], ["Genre", "genre"], ["Style", "style"], ["Mood", "mood"], ["Energy", "energy"],
    ["Made for", "use"], ["DAW", "daw"], ["Plugin", "plugin"], ["System", "os"], ["Key", "key"], ["Level", "skill"]];
  const detailFacts = [
    ...FIELDS.filter(([, f]) => (d.facets[f] || []).length).map(([t, f]) => `<dt>${t}</dt><dd>${esc(d.facets[f].map((v) => V.label(f, v)).join(", "))}</dd>`),
    d.bpm ? `<dt>BPM</dt><dd>${d.bpm[0] === d.bpm[1] ? d.bpm[0] : `${d.bpm[0]}–${d.bpm[1]}`}</dd>` : "",
    d.specs.sampleRate ? `<dt>Sample rate</dt><dd>${d.specs.sampleRate / 1000} kHz</dd>` : "",
    d.specs.bitDepth ? `<dt>Bit depth</dt><dd>${d.specs.bitDepth}-bit</dd>` : ""
  ].join("");
  const main = `${hero(crumbs, esc(p.category), p.title, byline(creator))}

    <section>
      <div class="wrap product" data-product-page="${esc(p.id)}">
        ${productCover(p, true, data.productTypes)}
        <div class="product-info">
          <p class="lede">${esc(p.description)}</p>
          <div class="buy-panel">
            <div class="buy-panel-head">
              <span class="price buy-price" data-price="${esc(p.id)}">${price}</span>
              <span class="buy-state" data-status="${esc(p.id)}">${buyable ? "Available now" : "Coming soon"}</span>
            </div>
            <div class="detail-buy buy" data-buy="${esc(p.id)}">
              ${buyable ? `<button class="btn" type="button" data-add-to-cart="${esc(p.id)}">Add to cart</button>` : `<span class="btn" aria-disabled="true">Coming soon</span>`}
            </div>
            ${buyable ? `<button class="btn ghost wish-btn" type="button" data-wish="${esc(p.id)}" aria-pressed="false">Save to wishlist</button>` : ""}
            <ul class="buy-points">
              <li>Digital download, in <a href="/library">Your Stacc</a> the moment the payment clears</li>
              <li>Checkout runs on Stripe; this site never sees your card</li>
              <li>Private links that expire after a few minutes · <a href="/refunds">Refund policy</a></li>
            </ul>
          </div>
          ${preview}
          ${(p.includes || []).length ? `<h2 class="included-head">What's inside</h2>
          <ul class="included">${p.includes.map((x) => `<li>${esc(x)}</li>`).join("")}</ul>` : ""}
          ${pacs.length ? `<h2 class="included-head">Pacs</h2>
          <ul class="included pacs">${pacs.map(({ pac, stacclet }) => `<li>${esc(pac.title)}${stacclet ? ` <span class="small-print">· ${esc(stacclet.title)} Stacclet</span>` : ""}</li>`).join("")}</ul>` : ""}
          <h2 class="included-head">Details</h2>
          <dl class="facts">
            <dt>Created by</dt><dd><a href="${esc(projectPath(creator.id))}">${esc(creator.name)}</a></dd>
            <dt>Sold by</dt><dd><a href="/about">${esc(SITE.name)}</a></dd>
            <dt>Type</dt><dd>${esc(p.category)}</dd>
            <dt>Delivery</dt><dd>Digital download</dd>
            ${detailFacts}
            <div data-size-row hidden><dt>Download</dt><dd data-size="${esc(p.id)}"></dd></div>
            ${release ? `<dt>Release</dt><dd><a href="${esc(releasePath(release))}">${esc(release.title)}</a></dd>` : ""}
            ${(p.tags || []).length ? `<dt>Tags</dt><dd class="tags">${p.tags.map((t) => `<span class="tag">${esc(t)}</span>`).join(" ")}</dd>` : ""}
            ${facts}
          </dl>
          ${licenseBox(SITE, data, p)}
        </div>
      </div>
    </section>

    <section class="similar-section" data-similar="${esc(p.id)}" hidden></section>
${others.length ? `
    <section class="alt">
      <div class="wrap">
        <div class="section-head"><h2>More from ${esc(creator.name)}</h2><a href="/shop?creator=${esc(encodeURIComponent(creator.id))}">All of it &rarr;</a></div>
        <ul class="tiles">${others.map(productTile).join("")}</ul>
      </div>
    </section>
` : ""}`;
  return { file: `shop/${p.id}.html`, page, html: shell(SITE, { page, section: "shop", styles: ["shop", "store", "detail"],
    scripts: ["data/product-types.js", "data/vocabulary.js", "js/product-card.js", "js/taste.js", "js/similar.js", "js/wishlist.js", "js/store.js"], main, look: creator }) };
}

// ---------- news post ----------
function newsPage(SITE, data, n) {
  const creator = creatorOf(data, n);
  const home = projectPath(creator.id);
  const url = abs(SITE, newsPath(n));
  const crumbs = [["Home", "/"], ...ownerCrumb(data, creator), [creator.name, home], ["News", home + "/news"], [n.title, newsPath(n)]];
  const release = data.releases.find((r) => r.id === n.release);
  const image = (release && release.artwork) || creator.image || SITE.image;
  const title = `${n.title}${projectSuffix(SITE, creator.name)}`;
  const description = clip(n.summary || n.title);
  const page = {
    path: newsPath(n),
    title,
    description,
    index: true,
    ogType: "article",
    image,
    og: { "article:published_time": n.date, ...(n.tag && { "article:section": n.tag }) },
    schema: [
      H.webPage(SITE, { path: newsPath(n), title, description }, "WebPage",
        { mainEntity: { "@id": url + "#article" }, breadcrumb: H.breadcrumbs(SITE, crumbs) }),
      H.article(SITE, n, url, image, creator)
    ]
  };
  const main = `${hero(crumbs, `${esc(n.tag || "Update")} · <time datetime="${esc(n.date)}">${fmtDate(n.date)}</time>`, n.title, "")}

    <section>
      <div class="wrap article">
        <div class="article-body">
          ${n.body || `<p>${esc(n.summary || "")}</p>`}
        </div>
        ${release ? `<a class="tile release-tile" href="${esc(releasePath(release))}">${release.artwork ? picture(release.artwork, "160px", false) : ""}<span><span class="tag">${esc(release.type)}</span><strong>${esc(release.title)}</strong><span>Release page &rarr;</span></span></a>` : ""}
      </div>
    </section>

    <section class="alt">
      <div class="wrap detail-more">
        <a class="btn ghost" href="${esc(home)}/news">All news</a>
        <a class="btn ghost" href="${esc(home)}/music">Music</a>
      </div>
    </section>`;
  return { file: newsPath(n).slice(1) + ".html", page, html: shell(SITE, { page, section: "news", styles: ["news", "detail"], scripts: [], main, project: creator, projectPage: "news" }) };
}

