// Builds each page's search metadata: title, description, robots, canonical, Open Graph, Twitter card and JSON-LD.
const { origin, abs, projectPath } = require("./data");

const START = "<!-- seo:start · generated by scripts/build.js from data/ and this page's title and description. Don't edit inside. -->";
const END = "<!-- seo:end -->";

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const isUrl = (u) => typeof u === "string" && /^https:\/\/[^/\s]+\.[^/\s]+/.test(u);
const profiles = (x) => (x.socials || []).filter((s) => isUrl(s.url)).map((s) => s.url);
// "2:27" -> "PT2M27S"
const isoDuration = (d) => {
  const [m, s] = String(d).split(":").map(Number);
  return `PT${m}M${s}S`;
};

const RELEASE_TYPES = { Single: "SingleRelease", EP: "EPRelease", Album: "AlbumRelease" };

// ---------- schema.org entities ----------
// AutoStacc is the WebSite and the Organization (it sells everything); each project is its own entity at its page.
const ids = (SITE) => ({ site: origin(SITE) + "/#website", org: origin(SITE) + "/#organization" });
const projectId = (SITE, project) => abs(SITE, projectPath(project.id)) + "#project";

function organization(SITE) {
  return {
    "@type": "Organization",
    "@id": ids(SITE).org,
    name: SITE.name,
    url: origin(SITE) + "/",
    description: SITE.description,
    logo: abs(SITE, SITE.logo),
    image: abs(SITE, SITE.image.src)
  };
}
// A named reference, so pages that don't carry the full Organization still say who publishes and sells.
const orgRef = (SITE) => ({ "@type": "Organization", "@id": ids(SITE).org, name: SITE.name, url: origin(SITE) + "/", logo: abs(SITE, SITE.logo) });

function website(SITE) {
  return {
    "@type": "WebSite",
    "@id": ids(SITE).site,
    url: origin(SITE) + "/",
    name: SITE.name,
    description: SITE.description,
    inLanguage: "en",
    publisher: orgRef(SITE)
  };
}

// Full project entity (MusicGroup for Glitches & Stitches): on the project's home and press pages.
function projectEntity(SITE, project) {
  const sameAs = profiles(project);
  return {
    "@type": project.entity || "Organization",
    "@id": projectId(SITE, project),
    name: project.name,
    ...(project.alternateNames && project.alternateNames.length && { alternateName: project.alternateNames }),
    url: abs(SITE, projectPath(project.id)),
    description: project.bio || project.summary,
    ...(project.genres && { genre: project.genres }),
    ...(project.image && { image: abs(SITE, project.image.src) }),
    ...(project.logo && { logo: abs(SITE, project.logo) }),
    ...(sameAs.length && { sameAs })
  };
}
const projectRef = (SITE, project) => ({ "@type": project.entity || "Organization", "@id": projectId(SITE, project), name: project.name, url: abs(SITE, projectPath(project.id)) });

function webPage(SITE, page, type = "WebPage", extra = {}) {
  return {
    "@type": type,
    "@id": abs(SITE, page.path) + "#webpage",
    url: abs(SITE, page.path),
    name: page.title,
    description: page.description,
    inLanguage: "en",
    isPartOf: { "@id": ids(SITE).site },
    ...extra
  };
}

function breadcrumbs(SITE, crumbs) {
  return {
    "@type": "BreadcrumbList",
    itemListElement: crumbs.map(([name, p], i) => ({ "@type": "ListItem", position: i + 1, name, item: abs(SITE, p) }))
  };
}

function itemList(SITE, items) {
  return {
    "@type": "ItemList",
    numberOfItems: items.length,
    itemListElement: items.map(([name, p], i) => ({ "@type": "ListItem", position: i + 1, name, url: abs(SITE, p) }))
  };
}

function album(SITE, r, url, project) {
  const links = (r.links || []).filter((l) => isUrl(l.url)).map((l) => l.url);
  return {
    "@type": "MusicAlbum",
    "@id": url + "#release",
    name: r.title,
    url,
    description: r.description,
    albumReleaseType: "https://schema.org/" + (RELEASE_TYPES[r.type] || "AlbumRelease"),
    byArtist: projectRef(SITE, project),
    datePublished: r.date,
    ...(r.artwork && { image: abs(SITE, r.artwork.src) }),
    numTracks: (r.tracks || []).length,
    track: {
      "@type": "ItemList",
      numberOfItems: (r.tracks || []).length,
      itemListElement: (r.tracks || []).map((t, i) => ({
        "@type": "ListItem",
        position: i + 1,
        item: {
          "@type": "MusicRecording",
          name: t.title,
          byArtist: projectRef(SITE, project),
          ...(t.duration && { duration: isoDuration(t.duration) }),
          ...(t.isrc && { isrcCode: t.isrc })
        }
      }))
    },
    ...(links.length && { sameAs: links })
  };
}

function product(SITE, p, url, release, project) {
  return {
    "@type": "Product",
    "@id": url + "#product",
    name: p.title,
    description: p.description,
    sku: p.id,
    category: p.category,
    url,
    ...(p.image && { image: abs(SITE, p.image.src) }),
    brand: { "@type": "Brand", name: project.name },
    ...(release && { isRelatedTo: { "@type": "MusicAlbum", name: release.title, url: abs(SITE, projectPath(release.project, "music", release.id)) } }),
    offers: {
      "@type": "Offer",
      url,
      price: Number(p.price).toFixed(2),
      priceCurrency: p.currency || SITE.currency || "USD",
      // Sold through the site's own store; drafts never get this far (they publish no Product data).
      availability: "https://schema.org/" + (p.draft ? "OutOfStock" : "InStock"),
      seller: orgRef(SITE)
    }
  };
}

function article(SITE, n, url, image, project) {
  return {
    "@type": "BlogPosting",
    "@id": url + "#article",
    headline: n.title,
    description: n.summary,
    datePublished: n.date,
    url,
    mainEntityOfPage: url,
    image: abs(SITE, image.src),
    author: projectRef(SITE, project),
    publisher: orgRef(SITE),
    ...(n.tag && { articleSection: n.tag }),
    inLanguage: "en"
  };
}

// ---------- the <head> block ----------
// page: { path, title, description, ownTitle, index, ogType, image, og: {extra property: value}, schema: [entities] }
function headBlock(SITE, page) {
  const image = page.image || SITE.image;
  const lines = [];
  const meta = (attr, key, value) => lines.push(`<meta ${attr}="${key}" content="${esc(value)}">`);
  if (!page.ownTitle) {
    lines.push(`<title>${esc(page.title)}</title>`);
    meta("name", "description", page.description);
  }
  // Only indexable pages name a canonical; a noindex page gets the robots tag (unless it writes its own).
  if (page.index) lines.push(`<link rel="canonical" href="${esc(abs(SITE, page.path))}">`);
  else if (!page.ownRobots) meta("name", "robots", "noindex, follow");
  meta("property", "og:site_name", SITE.name);
  meta("property", "og:locale", "en_US");
  meta("property", "og:type", page.ogType || "website");
  meta("property", "og:title", page.title);
  meta("property", "og:description", page.description);
  if (page.path) meta("property", "og:url", abs(SITE, page.path));
  meta("property", "og:image", abs(SITE, image.src));
  if (image.width) meta("property", "og:image:width", image.width);
  if (image.height) meta("property", "og:image:height", image.height);
  meta("property", "og:image:alt", image.alt);
  for (const [k, v] of Object.entries(page.og || {})) meta("property", k, v);
  meta("name", "twitter:card", "summary_large_image");
  meta("name", "twitter:title", page.title);
  meta("name", "twitter:description", page.description);
  meta("name", "twitter:image", abs(SITE, image.src));
  meta("name", "twitter:image:alt", image.alt);
  if (page.schema && page.schema.length) {
    // "<" is escaped so data can never close the script tag early.
    const json = JSON.stringify({ "@context": "https://schema.org", "@graph": page.schema }, null, 1).replace(/</g, "\\u003c");
    lines.push(`<script type="application/ld+json">\n${json}\n  </script>`);
  }
  return [START, ...lines, END].map((l) => "  " + l).join("\n").trimStart();
}

module.exports = {
  START, END, esc, isUrl, isoDuration,
  organization, website, projectEntity, projectRef, webPage, breadcrumbs, itemList, album, product, article, headBlock
};
