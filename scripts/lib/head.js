// Builds each page's search metadata: title, description, robots, canonical, Open Graph, Twitter card and JSON-LD.
const { origin, abs } = require("./data");

const START = "<!-- seo:start · generated by scripts/build.js from data/ and this page's title and description. Don't edit inside. -->";
const END = "<!-- seo:end -->";

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const isUrl = (u) => typeof u === "string" && /^https:\/\/[^/\s]+\.[^/\s]+/.test(u);
const profiles = (SITE) => (SITE.socials || []).filter((s) => isUrl(s.url)).map((s) => s.url);
// "2:27" -> "PT2M27S"
const isoDuration = (d) => {
  const [m, s] = String(d).split(":").map(Number);
  return `PT${m}M${s}S`;
};

const RELEASE_TYPES = { Single: "SingleRelease", EP: "EPRelease", Album: "AlbumRelease" };

// ---------- schema.org entities ----------
const ids = (SITE) => ({ site: origin(SITE) + "/#website", artist: origin(SITE) + "/#artist" });

// Full artist entity: on the home and press pages. Elsewhere a short reference is enough.
function artist(SITE) {
  const sameAs = profiles(SITE);
  return {
    "@type": "MusicGroup",
    "@id": ids(SITE).artist,
    name: SITE.artist,
    url: origin(SITE) + "/",
    description: SITE.bio || SITE.description,
    genre: SITE.genres,
    image: abs(SITE, SITE.image.src),
    logo: abs(SITE, SITE.logo),
    ...(sameAs.length && { sameAs })
  };
}
const artistRef = (SITE) => ({ "@type": "MusicGroup", "@id": ids(SITE).artist, name: SITE.artist, url: origin(SITE) + "/" });

function website(SITE) {
  return {
    "@type": "WebSite",
    "@id": ids(SITE).site,
    url: origin(SITE) + "/",
    name: SITE.artist,
    ...(SITE.alternateNames && SITE.alternateNames.length && { alternateName: SITE.alternateNames }),
    description: SITE.description,
    inLanguage: "en",
    publisher: { "@id": ids(SITE).artist }
  };
}

function webPage(SITE, page, type = "WebPage", extra = {}) {
  return {
    "@type": type,
    "@id": abs(SITE, page.path) + "#webpage",
    url: abs(SITE, page.path),
    name: page.title,
    description: page.description,
    inLanguage: "en",
    isPartOf: { "@id": ids(SITE).site },
    ...extra
  };
}

function breadcrumbs(SITE, crumbs) {
  return {
    "@type": "BreadcrumbList",
    itemListElement: crumbs.map(([name, p], i) => ({ "@type": "ListItem", position: i + 1, name, item: abs(SITE, p) }))
  };
}

function itemList(SITE, items) {
  return {
    "@type": "ItemList",
    numberOfItems: items.length,
    itemListElement: items.map(([name, p], i) => ({ "@type": "ListItem", position: i + 1, name, url: abs(SITE, p) }))
  };
}

function album(SITE, r, url) {
  const links = (r.links || []).filter((l) => isUrl(l.url)).map((l) => l.url);
  return {
    "@type": "MusicAlbum",
    "@id": url + "#release",
    name: r.title,
    url,
    description: r.description,
    albumReleaseType: "https://schema.org/" + (RELEASE_TYPES[r.type] || "AlbumRelease"),
    byArtist: artistRef(SITE),
    datePublished: r.date,
    ...(r.artwork && { image: abs(SITE, r.artwork.src) }),
    numTracks: (r.tracks || []).length,
    track: {
      "@type": "ItemList",
      numberOfItems: (r.tracks || []).length,
      itemListElement: (r.tracks || []).map((t, i) => ({
        "@type": "ListItem",
        position: i + 1,
        item: {
          "@type": "MusicRecording",
          name: t.title,
          byArtist: artistRef(SITE),
          ...(t.duration && { duration: isoDuration(t.duration) }),
          ...(t.isrc && { isrcCode: t.isrc })
        }
      }))
    },
    ...(links.length && { sameAs: links })
  };
}

function product(SITE, p, url, release) {
  return {
    "@type": "Product",
    "@id": url + "#product",
    name: p.title,
    description: p.description,
    sku: p.id,
    category: p.category,
    url,
    ...(p.image && { image: abs(SITE, p.image.src) }),
    brand: { "@type": "Brand", name: SITE.artist },
    ...(release && { isRelatedTo: { "@type": "MusicAlbum", name: release.title, url: abs(SITE, "/music/" + release.id) } }),
    offers: {
      "@type": "Offer",
      url,
      price: Number(p.price).toFixed(2),
      priceCurrency: SITE.currency || "USD",
      // Bought through the hosted checkout; with no checkout link yet it can't be bought.
      availability: "https://schema.org/" + (isUrl(p.checkoutUrl) ? "InStock" : "OutOfStock"),
      seller: { "@id": ids(SITE).artist }
    }
  };
}

function article(SITE, n, url, image) {
  return {
    "@type": "BlogPosting",
    "@id": url + "#article",
    headline: n.title,
    description: n.summary,
    datePublished: n.date,
    url,
    mainEntityOfPage: url,
    image: abs(SITE, image.src),
    author: artistRef(SITE),
    publisher: artistRef(SITE),
    ...(n.tag && { articleSection: n.tag }),
    inLanguage: "en"
  };
}

// ---------- the <head> block ----------
// page: { path, title, description, ownTitle, index, ogType, image, og: {extra property: value}, schema: [entities] }
function headBlock(SITE, page) {
  const image = page.image || SITE.image;
  const lines = [];
  const meta = (attr, key, value) => lines.push(`<meta ${attr}="${key}" content="${esc(value)}">`);
  if (!page.ownTitle) {
    lines.push(`<title>${esc(page.title)}</title>`);
    meta("name", "description", page.description);
  }
  if (!page.index && !page.ownRobots) meta("name", "robots", "noindex, follow");
  else lines.push(`<link rel="canonical" href="${esc(abs(SITE, page.path))}">`);
  meta("property", "og:site_name", SITE.artist);
  meta("property", "og:locale", "en_US");
  meta("property", "og:type", page.ogType || "website");
  meta("property", "og:title", page.title);
  meta("property", "og:description", page.description);
  if (page.path) meta("property", "og:url", abs(SITE, page.path));
  meta("property", "og:image", abs(SITE, image.src));
  if (image.width) meta("property", "og:image:width", image.width);
  if (image.height) meta("property", "og:image:height", image.height);
  meta("property", "og:image:alt", image.alt);
  for (const [k, v] of Object.entries(page.og || {})) meta("property", k, v);
  meta("name", "twitter:card", "summary_large_image");
  meta("name", "twitter:title", page.title);
  meta("name", "twitter:description", page.description);
  meta("name", "twitter:image", abs(SITE, image.src));
  meta("name", "twitter:image:alt", image.alt);
  if (page.schema && page.schema.length) {
    // "<" is escaped so data can never close the script tag early.
    const json = JSON.stringify({ "@context": "https://schema.org", "@graph": page.schema }, null, 1).replace(/</g, "\\u003c");
    lines.push(`<script type="application/ld+json">\n${json}\n  </script>`);
  }
  return [START, ...lines, END].map((l) => "  " + l).join("\n").trimStart();
}

module.exports = {
  START, END, esc, isUrl, isoDuration,
  artist, artistRef, website, webPage, breadcrumbs, itemList, album, product, article, headBlock
};
