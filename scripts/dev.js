// Runs the whole site locally like production: static pages from dist/ plus the store API (Pages Functions), with a
// local D1 database and R2 buckets (Wrangler, installed by `npm install`). Test mode only: mock payments, emails kept
// in the database (see /api/dev/outbox), test products (test/support/catalog-fixtures.js) for sale, sample files to
// download, and test project content. Nothing touches Cloudflare.
// Usage: npm run dev  (or node scripts/dev.js [--port 8788] [--fresh])   then open http://localhost:8788/
// Tests start it with startDevServer() and their own port, state folder and variables; several can start at once in one
// process (setup doesn't block), as long as the site is built beforehand and each passes build: false.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { spawn, execFile, execFileSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const WRANGLER = path.join(ROOT, "node_modules", ".bin", "wrangler");

// Each Wrangler command costs about two seconds of start-up, so the local setup runs independent ones side by side.
// opts.track: a Set that holds the running process, so a server stopped during setup can end it.
function wrangler(args, opts = {}) {
  const env = { ...process.env, WRANGLER_SEND_METRICS: "false", ...opts.env };
  let child;
  const done = new Promise((resolve, reject) => {
    if (opts.quiet) child = execFile(WRANGLER, args, { cwd: ROOT, env }, (e, out, err) => (e ? reject(Object.assign(e, { message: `${e.message}\n${err}` })) : resolve(out)));
    else child = spawn(WRANGLER, args, { cwd: ROOT, env, stdio: "inherit" })
      .on("error", reject).on("close", (code) => (code ? reject(new Error(`wrangler ${args.join(" ")} exited ${code}`)) : resolve("")));
  });
  if (opts.track) { opts.track.add(child); done.finally(() => opts.track.delete(child)).catch(() => {}); }
  return done;
}

// Secrets for local development only, generated once into .dev.vars (gitignored). Never real keys. An older file gains
// the test first-party owner it lacks.
const OWNERS = "FIRST_PARTY_OWNERS=autostacc=owner@autostacc.test";
function ensureDevVars() {
  const file = path.join(ROOT, ".dev.vars");
  if (fs.existsSync(file)) {
    if (!/^FIRST_PARTY_OWNERS=/m.test(fs.readFileSync(file, "utf8"))) fs.appendFileSync(file, `\n${OWNERS}\n`);
    return;
  }
  const rand = () => crypto.randomBytes(32).toString("hex");
  fs.writeFileSync(file, [
    "# Local development secrets (generated by scripts/dev.js, gitignored). Never put real keys here.",
    `BETTER_AUTH_SECRET=${rand()}`,
    `DOWNLOAD_SIGNING_SECRET=${rand()}`,
    "# Accounts with these emails are admins once verified.",
    "ADMIN_EMAILS=admin@autostacc.test",
    "# First-party creators' owners (<creator>=<email>), once verified (#172).",
    OWNERS,
    ""
  ].join("\n"));
  console.log("dev: wrote .dev.vars with fresh local secrets");
}

// Local-only test data. data/ sells nothing (products, Stacclets and Pacs are made in the Studio, #176), so the test
// products, the frayed-signals Stacclet and Pacs and a test event come from test/support/catalog-fixtures.js (rows
// shaped as the retired catalog sync wrote them, source 'catalog'), plus three extra test products and one small file
// per product (the sample pack's tagged with a Pac and kind), a second project without polls, test polls (open, closed,
// and one for that project), and the real release and news post the content migration seeds where the project exists
// (replayed here: locally the catalog adds the project after the migrations; the news row stays hidden, #174).
const fileIdFor = (productId) => "pf_" + [...crypto.createHash("sha256").update(productId).digest("hex").slice(0, 16)].map((c) => "abcdefghijklmnop"[parseInt(c, 16)]).join("");
// The seed statements of the migrations that fill project content (each skips itself when its row is already there).
function contentSeedSql() {
  const dir = path.join(ROOT, "db", "migrations");
  return fs.readdirSync(dir).filter((f) => f.endsWith(".sql")).sort().flatMap((f) =>
    fs.readFileSync(path.join(dir, f), "utf8").replace(/^--.*$/gm, "").split(/;\s*\n/).map((x) => x.trim())
      .filter((x) => /^(INSERT INTO project_(releases|news|events)|UPDATE projects SET look)\b/.test(x)).map((x) => x + ";"));
}
function devSeed(stateDir) {
  const { loadData } = require("./lib/data");
  const fixtures = require("../test/support/catalog-fixtures.js");
  const data = loadData();
  const products = fixtures.PRODUCTS.map((p) => p.id);
  const extra = [
    ["dev-unpublished", "Unpublished test item", 500, 0, 0],
    ["dev-paused", "Paused test item", 500, 1, 1],
    ["dev-free", "Free test item", 0, 1, 0]
  ];
  const T = "strftime('%Y-%m-%dT%H:%M:%fZ','now')";
  const poll = (id, project, opens, closes) => `INSERT OR REPLACE INTO polls (id, project_id, question, options, opens_at, closes_at, published, created_at, updated_at)
       VALUES ('${id}', '${project}', 'Test poll', '[{"id":"finish-it","label":"Finish it"},{"id":"scrap-it","label":"Scrap it"}]', ${opens}, ${closes}, 1, ${T}, ${T});`;
  const sql = [
    ...fixtures.fixtureSql(data.productTypes, data.projects),
    `INSERT OR REPLACE INTO projects (id, name, features, published, created_at, updated_at) VALUES ('dev-other', 'Other test project', '["store"]', 1, ${T}, ${T});`,
    poll("dev-poll", "glitches-and-stitches", "NULL", "NULL"),
    poll("dev-closed-poll", "glitches-and-stitches", "NULL", "'2000-01-01T00:00:00.000Z'"),
    poll("dev-other-poll", "dev-other", "NULL", "NULL"),
    ...contentSeedSql(),
    ...extra.map(([id, title, cents, published, paused]) =>
      `INSERT OR REPLACE INTO products (id, title, description, type, price_cents, currency, tags, metadata, featured, published, sales_paused, max_quantity, created_at, updated_at)
       VALUES ('${id}', '${title}', 'Local test product.', 'other', ${cents}, 'USD', '[]', '{}', 0, ${published}, ${paused}, 1, strftime('%Y-%m-%dT%H:%M:%fZ','now'), strftime('%Y-%m-%dT%H:%M:%fZ','now'));`),
    "UPDATE products SET project_id = 'glitches-and-stitches' WHERE id LIKE 'dev-%';",
    ...[...products, ...extra.map((e) => e[0])].map((id) =>
      `INSERT OR IGNORE INTO product_files (id, product_id, r2_key, filename, label, content_type, size_bytes, sort, active, created_at)
       VALUES ('${fileIdFor(id)}', '${id}', 'dev/${id}/readme.txt', '${id}-readme.txt', 'Test file', 'text/plain', 64, 0, 1, strftime('%Y-%m-%dT%H:%M:%fZ','now'));`),
    "UPDATE product_files SET pac_id = 'frayed-signals-samples', kind = 'samples' WHERE product_id = 'sample-pack-vol1';"
  ];
  const seedFile = path.join(stateDir, "dev-seed.sql");
  fs.writeFileSync(seedFile, sql.join("\n") + "\n");
  return { seedFile, ids: [...products, ...extra.map((e) => e[0])] };
}

// Prepares the local database and storage, then starts `wrangler pages dev`. Returns { url, ready, stop, log }; `child` is
// set once Wrangler is spawned. build: false skips build.js and dist.js (the caller built dist/ already; tests do, so
// stores starting together don't rewrite the files another is serving). inspectorPort: a fixed devtools port, for stores
// starting together (they would race for Wrangler's default); left out, Wrangler picks a free one.
function startDevServer({ port = 8788, stateDir = path.join(ROOT, ".wrangler", "state"), vars = {}, fresh = false, quiet = false, build = true, inspectorPort } = {}) {
  ensureDevVars();
  if (fresh) fs.rmSync(stateDir, { recursive: true, force: true });
  fs.mkdirSync(stateDir, { recursive: true });
  if (build) {
    execFileSync("node", [path.join(ROOT, "scripts/build.js")], { cwd: ROOT, stdio: quiet ? "pipe" : "inherit" });
    execFileSync("node", [path.join(ROOT, "scripts/dist.js")], { cwd: ROOT, stdio: quiet ? "pipe" : "inherit" });
  } else if (!fs.existsSync(path.join(ROOT, "dist", "index.html"))) {
    throw new Error("dist/ is missing: run `npm run site` first (npm run test:api, test:browser and test:store do)");
  }
  const url = `http://localhost:${port}`;
  let log = "", stopped = false;
  const server = { url, child: null, log: () => log, fileIdFor };
  const setup = new Set();
  server.stop = () => { stopped = true; setup.forEach((c) => c.kill("SIGTERM")); if (server.child) server.child.kill("SIGTERM"); };
  server.ready = (async () => {
    const q = { quiet: true, track: setup };
    const { seedFile, ids } = devSeed(stateDir);
    // The catalog and the test data go in as one file, after the migrations.
    const dataFile = path.join(stateDir, "dev-data.sql");
    fs.writeFileSync(dataFile, fs.readFileSync(path.join(ROOT, "db/catalog.sql"), "utf8") + "\n" + fs.readFileSync(seedFile, "utf8"));
    // One step after another: Wrangler's local D1 and R2 share state on disk, and running them together sometimes
    // fails with "database is locked".
    await wrangler(["d1", "migrations", "apply", "DB", "--local", "--persist-to", stateDir], { ...q, env: { CI: "1" } });
    await wrangler(["d1", "execute", "DB", "--local", "--persist-to", stateDir, "--file", dataFile], q);
    // Every sample file in one Wrangler call, one at a time inside it (local storage refuses concurrent writes).
    const manifest = path.join(stateDir, "dev-files.json");
    fs.writeFileSync(manifest, JSON.stringify(ids.map((id) => {
      const file = path.join(stateDir, `dev-file-${id}.txt`);
      fs.writeFileSync(file, `Test download for ${id}. If you can read this, the entitlement check let you in.\n`);
      return { key: `dev/${id}/readme.txt`, file };
    })));
    await wrangler(["r2", "bulk", "put", "autostacc-files-dev", "--local", "--persist-to", stateDir, "--filename", manifest, "--concurrency", "1", "--force"], q);
    if (stopped) throw new Error("dev server stopped before it started");
    const args = ["pages", "dev", "dist", "--port", String(port), ...(inspectorPort ? ["--inspector-port", String(inspectorPort)] : []), "--ip", "127.0.0.1", "--persist-to", stateDir, "--show-interactive-dev-session=false",
      ...Object.entries({ SITE_URL: url, ...vars }).flatMap(([k, v]) => ["--binding", `${k}=${v}`])];
    const child = server.child = spawn(WRANGLER, args, { cwd: ROOT, env: { ...process.env, WRANGLER_SEND_METRICS: "false" }, stdio: ["ignore", "pipe", "pipe"] });
    const onData = (d) => { log += d; if (!quiet) process.stdout.write(d); };
    child.stdout.on("data", onData);
    child.stderr.on("data", onData);
    for (let i = 0; i < 240; i++) {
      if (child.exitCode !== null) throw new Error("wrangler exited:\n" + log.slice(-3000));
      try {
        const res = await fetch(`${url}/api/account`);
        if (res.status === 200) return url;
      } catch {}
      await new Promise((r) => setTimeout(r, 500));
    }
    throw new Error("dev server did not start:\n" + log.slice(-3000));
  })();
  return server;
}

module.exports = { startDevServer, fileIdFor };

if (require.main === module) {
  const arg = (name, dflt) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : dflt; };
  const server = startDevServer({ port: Number(arg("--port", 8788)), fresh: process.argv.includes("--fresh") });
  server.ready.then((url) => console.log(`\ndev: site and store API on ${url}/  (test mode: mock payments, emails at ${url}/api/dev/outbox)\n`))
    .catch((e) => { console.error(e.message); process.exit(1); });
  process.on("SIGINT", () => { if (server.child) server.child.kill("SIGINT"); process.exit(0); });
}
